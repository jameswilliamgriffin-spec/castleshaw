#!/usr/bin/env python3
"""Build responsive AVIF, WebP and JPEG versions of every image in the imagery manifest.

Run from site/:  python3 scripts/imagery.py
Reads   v2/src/content/imagery.json  ("images": id -> {source, from})
Writes  public/shared/images/gen/<id>-<width>.{avif,webp,jpg}
Updates the manifest with each image's width, height and available widths,
and writes qa/IMAGERY-SIZES.md with every file size.
Uses Pillow only (already installed); no npm dependency.
"""
import json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, 'v2/src/content/imagery.json')
OUT = os.path.join(ROOT, 'public/shared/images/gen')
STEPS = [480, 768, 1200, 1536]
Q = {'avif': 52, 'webp': 74, 'jpg': 80}

m = json.load(open(MANIFEST))
os.makedirs(OUT, exist_ok=True)
rows = []
for iid, im in m['images'].items():
    src = Image.open(os.path.join(ROOT, im['from'])).convert('RGB')
    w, h = src.size
    widths = [s for s in STEPS if s < w] + [w]
    for tw in widths:
        th = round(h * tw / w)
        r = src if tw == w else src.resize((tw, th), Image.LANCZOS)
        for ext in ('avif', 'webp', 'jpg'):
            p = os.path.join(OUT, f'{iid}-{tw}.{ext}')
            if ext == 'jpg':
                r.save(p, 'JPEG', quality=Q[ext], optimize=True, progressive=True)
            elif ext == 'webp':
                r.save(p, 'WEBP', quality=Q[ext], method=6)
            else:
                r.save(p, 'AVIF', quality=Q[ext], speed=4)
            rows.append((iid, tw, ext, os.path.getsize(p)))
    im.update({'w': w, 'h': h, 'widths': widths})

json.dump(m, open(MANIFEST, 'w'), indent=2, ensure_ascii=False)

kb = lambda b: f'{b / 1024:.0f} KB'
lines = ['# Imagery file sizes', '', 'Generated by `scripts/imagery.py`. Browsers load one file per image: AVIF where supported, else WebP, else JPEG, at the width that suits the screen.', '',
         '| Image | Source | Widths | Largest AVIF | Largest WebP | Largest JPEG | All files |', '|---|---|---|---|---|---|---|']
for iid, im in m['images'].items():
    mine = [r for r in rows if r[0] == iid]
    big = max(im['widths'])
    size = {e: next(r[3] for r in mine if r[1] == big and r[2] == e) for e in ('avif', 'webp', 'jpg')}
    lines.append(f"| `{iid}` | {im['source']} | {', '.join(map(str, im['widths']))} | {kb(size['avif'])} | {kb(size['webp'])} | {kb(size['jpg'])} | {kb(sum(r[3] for r in mine))} |")
open(os.path.join(ROOT, 'qa/IMAGERY-SIZES.md'), 'w').write('\n'.join(lines) + '\n')
print(f'{len(m["images"])} images, {len(rows)} files, {kb(sum(r[3] for r in rows))} in all')
