// Writes v2/<path>/index.html for every page in v2/src/site.mjs.
// Each entry sets its depth (so every URL stays relative) and names its page;
// one shared script (v2/src/inner.jsx) renders whichever page it is.
// Runs automatically before `npm run dev` and `npm run build`.
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PAGES, CUSTOM_ENTRY, DESCRIPTIONS, TITLES, PRELOAD } from '../v2/src/site.mjs'
import { FAQ } from '../v2/src/content/advice.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const v2 = resolve(here, '../v2')
// Structured data for search engines, where a page has something worth describing.
function structured(path) {
  if (path !== 'advice-and-guidance/') return ''
  const data = [
    {
      '@context': 'https://schema.org', '@type': 'GovernmentService',
      name: 'Educational Visits Advice and Guidance Service',
      serviceType: 'Educational visits advice, approval and training',
      description: DESCRIPTIONS[path],
      areaServed: ['Oldham', 'Greater Manchester', 'North West England'],
      audience: { '@type': 'Audience', audienceType: 'Schools, academies, trusts, colleges and youth services' },
      provider: { '@type': 'GovernmentOrganization', name: 'Oldham Council, Castleshaw Centre', telephone: '+44 161 770 8595', email: 'castleshaw.centre@oldham.gov.uk', address: { '@type': 'PostalAddress', streetAddress: 'Waterworks Road, Delph', addressLocality: 'Oldham', postalCode: 'OL3 5LZ', addressCountry: 'GB' } },
    },
    { '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity: FAQ.map((f) => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } })) },
  ]
  return `\n  <script type="application/ld+json">${JSON.stringify(data).replace(/</g, '\\u003c')}</script>`
}

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;')

let n = 0
for (const p of PAGES) {
  if (CUSTOM_ENTRY.has(p.path)) continue
  const depth = p.path.split('/').filter(Boolean).length
  const home = '../'.repeat(depth)
  const root = home + '../'
  const title = `${TITLES[p.path] || p.long || p.title} | Castleshaw Centre`
  const desc = DESCRIPTIONS[p.path] || 'The Castleshaw Centre, Delph, Oldham.'
  const html = `<!doctype html>
<!-- Generated by scripts/gen-pages.mjs from v2/src/site.mjs. Edit those, not this file. -->
<html lang="en-GB">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(desc)}" />
  <link rel="icon" href="${root}shared/images/logo.jpg" />${PRELOAD[p.path] ? `\n  <link rel="preload" as="image" href="${root}${PRELOAD[p.path]}" fetchpriority="high" />` : ''}${structured(p.path)}
  <script>
    if (!/\\/$|\\.html$/.test(location.pathname)) location.replace(location.pathname + '/' + location.search + location.hash)
    window.__ROOT = '${root}'; window.__HOME = '${home}'; window.__PAGE = '${p.path}'
  </script>
</head>
<body><div id="root"></div><script type="module" src="${home}src/inner.jsx"></script></body>
</html>
`
  const out = resolve(v2, p.path, 'index.html')
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, html)
  n++
}
console.log(`gen-pages: wrote ${n} v2 page entries`)
